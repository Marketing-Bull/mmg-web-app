#!/usr/bin/env node
/*
  Keeps the schema.org Event JSON-LD that is committed in index.html in step
  with data/events.json.

    node scripts/sync-static-events.mjs            # rewrite the block
    node scripts/sync-static-events.mjs --check    # exit 1 if it is out of step

  Why a committed copy exists at all: assets/js/content.js builds this markup
  in the browser, which is right for Googlebot (it renders JavaScript) but
  invisible to any crawler that reads raw HTML. The copy here is for those.

  It is generated by loading content.js itself and calling the same builder
  the browser uses, so the two cannot disagree about the format. They can
  disagree about how recent the data is, which is why the script re-runs
  whenever events.json changes (CI fails otherwise), and why content.js
  replaces this block with the live list as soon as it loads.

  The block records the Florida date it was built for (data-generated).
  --check rebuilds for that date rather than for today, so it only fails when
  the data changed, never just because an event's date went by.
*/
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { pathToFileURL } from "node:url";

const INDEX = "index.html";
const EVENTS = "data/events.json";
const CONTENT_JS = "assets/js/content.js";

// <script type="application/ld+json" data-event-schema data-generated="...">…</script>
const BLOCK = /[ \t]*<script type="application\/ld\+json" data-event-schema data-generated="[^"]*">[\s\S]*?<\/script>\n/;
const FIRST_LD = /([ \t]*<script type="application\/ld\+json">[\s\S]*?<\/script>\n)/;

export function floridaDateKey(date = new Date()) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: "America/New_York",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);
  const v = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${v.year}-${v.month}-${v.day}`;
}

// Runs the browser script's own schema builder with "now" pinned to a given
// Florida date, so the output is reproducible and testable.
export function buildSchemaNodes(events, todayKey) {
  const fixed = new Date(`${todayKey}T16:00:00Z`).getTime();
  class FixedDate extends Date {
    constructor(...args) {
      if (args.length === 0) super(fixed);
      else super(...args);
    }
    static now() {
      return fixed;
    }
  }
  const mod = { exports: {} };
  vm.runInNewContext(readFileSync(CONTENT_JS, "utf8"), { module: mod, Date: FixedDate });
  // Objects built inside the vm carry that context's prototypes; a JSON
  // round-trip hands back plain objects that compare equal everywhere.
  return JSON.parse(JSON.stringify(mod.exports.eventSchemaNodes(events)));
}

function renderBlock(nodes, todayKey) {
  // Same escaping content.js applies, and indented so the diff stays readable.
  const json = JSON.stringify(nodes.length === 1 ? nodes[0] : nodes, null, 2)
    .replace(/</g, "\\u003c")
    .split("\n")
    .map((line) => "      " + line)
    .join("\n");
  return `    <script type="application/ld+json" data-event-schema data-generated="${todayKey}">\n${json}\n    </script>\n`;
}

function readEvents() {
  const data = JSON.parse(readFileSync(EVENTS, "utf8"));
  return Array.isArray(data.events) ? data.events : [];
}

// What the committed block currently says, or null if there is none.
export function readStaticBlock(html) {
  const match = html.match(BLOCK);
  if (!match) return null;
  const generated = (match[0].match(/data-generated="([^"]*)"/) || [])[1] || "";
  const body = match[0].replace(/^[\s\S]*?<script[^>]*>/, "").replace(/<\/script>\s*$/, "");
  return { generated, data: JSON.parse(body) };
}

// Compares the committed block with a rebuild for the date it was built for.
export function checkStaticEvents(html = readFileSync(INDEX, "utf8"), events = readEvents(), todayKey = floridaDateKey()) {
  const current = readStaticBlock(html);
  const builtFor = current && current.generated ? current.generated : todayKey;
  const nodes = buildSchemaNodes(events, builtFor);
  const expected = nodes.length ? JSON.stringify(nodes.length === 1 ? nodes[0] : nodes) : null;
  const actual = current ? JSON.stringify(current.data) : null;
  const upcomingNow = buildSchemaNodes(events, todayKey).length;
  const listed = current ? [].concat(current.data).length : 0;
  return {
    inStep: expected === actual,
    builtFor,
    // Not a failure: events go by without anyone committing. Worth a nudge.
    stale: current ? listed > upcomingNow || (listed < upcomingNow && expected !== null) : false,
    listed,
    upcomingNow,
  };
}

export function syncStaticEvents(html, events, todayKey) {
  const nodes = buildSchemaNodes(events, todayKey);
  const had = BLOCK.test(html);
  if (!nodes.length) return html.replace(BLOCK, "");
  const block = renderBlock(nodes, todayKey);
  if (had) return html.replace(BLOCK, block);
  if (!FIRST_LD.test(html)) throw new Error("could not find the JSON-LD block in index.html to place the events after");
  return html.replace(FIRST_LD, (whole) => whole + block);
}

function main(argv) {
  const html = readFileSync(INDEX, "utf8");
  const events = readEvents();
  const today = floridaDateKey();

  if (argv.includes("--check")) {
    const result = checkStaticEvents(html, events, today);
    if (!result.inStep) {
      console.error("index.html event schema is OUT OF DATE with data/events.json — run: node scripts/sync-static-events.mjs");
      return 1;
    }
    console.log(`index.html event schema is in step (built for ${result.builtFor}, ${result.listed} event(s)).`);
    if (result.stale) {
      console.log(`  note: ${result.upcomingNow} event(s) are upcoming today; re-run the sync to refresh the committed copy.`);
    }
    return 0;
  }

  const next = syncStaticEvents(html, events, today);
  if (next === html) {
    console.log("index.html event schema already up to date.");
    return 0;
  }
  writeFileSync(INDEX, next);
  console.log(`rewrote the event schema in index.html for ${today} (${buildSchemaNodes(events, today).length} upcoming event(s)).`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main(process.argv.slice(2)));
}
